-- Migracion 023: vínculo explícito entre movimientos de caja y su venta/pago,
-- tabla de auditoría de correcciones y menús nuevos.
--
-- Aplicar con: node api/scripts/migrate.js
--
-- CONTEXTO
-- El cliente necesita corregir ventas y cobros de turnos ya cerrados (método
-- de pago mal elegido, venta duplicada, venta olvidada) sin tocar la caja
-- abierta de hoy. Para eso hace falta saber con certeza qué movimiento de
-- `registrodiariocaja` corresponde a qué venta o pago:
--   - Ventas: el detalle termina en "N°: <VentaId>", así que se recupera bien.
--   - Pagos de suscripción: el detalle es "Pago suscripción #<SuscripcionId>
--     - <Método>" y NO lleva el PagoId. Con dos cobros del mismo método sobre
--     la misma suscripción no hay forma de distinguirlos por texto.
--
-- COLUMNAS NUEVAS EN registrodiariocaja
--   ventaid     venta a la que pertenece el movimiento (venta o cobro crédito).
--   pagoid      pago de suscripción al que pertenece el movimiento.
--   aperturaref RegistroDiarioCajaId de la apertura del turno al que pertenece
--               el movimiento. Sólo lo completan las correcciones: un turno
--               se arma por rango de ids (apertura → cierre), y una fila
--               insertada hoy siempre tiene id mayor que el cierre de ayer.
--               NULL = vale la regla por rango de ids, como hasta ahora.
-- Sin FK: los movimientos son el rastro contable y deben sobrevivir aunque
-- se borre la venta o el pago.
--
-- BACKFILL
--   ventaid: desde el texto del detalle (venta.controller y
--            ventacreditopago.controller).
--   pagoid:  sólo cuando la correspondencia es única en las dos direcciones
--            (suscripción + monto + método + usuario + día). Los dudosos
--            quedan en NULL y se resuelven a mano desde la pantalla de
--            corrección.
--
-- Idempotente.

BEGIN;

ALTER TABLE registrodiariocaja ADD COLUMN IF NOT EXISTS ventaid     bigint;
ALTER TABLE registrodiariocaja ADD COLUMN IF NOT EXISTS pagoid      integer;
ALTER TABLE registrodiariocaja ADD COLUMN IF NOT EXISTS aperturaref integer;

CREATE INDEX IF NOT EXISTS idx_rdc_ventaid
  ON registrodiariocaja (ventaid) WHERE ventaid IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_rdc_pagoid
  ON registrodiariocaja (pagoid) WHERE pagoid IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_rdc_aperturaref
  ON registrodiariocaja (aperturaref) WHERE aperturaref IS NOT NULL;

-- Backfill ventaid ---------------------------------------------------------
UPDATE registrodiariocaja r
SET ventaid = substring(r.registrodiariocajadetalle FROM 'N°: (\d+)$')::bigint
WHERE r.ventaid IS NULL
  AND r.tipogastoid = 2
  AND (r.registrodiariocajadetalle LIKE 'Venta %N°: %'
       OR r.registrodiariocajadetalle LIKE 'Cobro Crédito %N°: %')
  AND substring(r.registrodiariocajadetalle FROM 'N°: (\d+)$') IS NOT NULL;

-- Backfill pagoid ----------------------------------------------------------
-- Candidatos: cada movimiento "Pago suscripción #S - X" contra cada pago de
-- la suscripción S con el mismo monto, el mismo día, el mismo usuario y el
-- grupo que corresponde al método (constants/pagoTipos.js).
WITH candidatos AS (
  SELECT r.registrodiariocajaid AS rid, p.pagoid AS pid
  FROM registrodiariocaja r
  JOIN pago p
    ON p.suscripcionid =
         substring(r.registrodiariocajadetalle FROM '^Pago suscripción #(\d+)')::integer
   AND p.pagomonto = r.registrodiariocajamonto
   AND p.pagofecha = DATE(r.registrodiariocajafecha)
   AND p.pagousuarioid::text = r.usuarioid::text
   AND r.tipogastogrupoid = CASE p.pagotipo
         WHEN 'CO' THEN 1 WHEN 'CR' THEN 3 WHEN 'PO' THEN 4
         WHEN 'VO' THEN 5 WHEN 'TR' THEN 6 ELSE 1 END
  WHERE r.pagoid IS NULL
    AND r.tipogastoid = 2
    AND r.registrodiariocajadetalle LIKE 'Pago suscripci%#%'
),
unicos AS (
  SELECT rid, pid FROM candidatos c
  WHERE (SELECT COUNT(*) FROM candidatos x WHERE x.rid = c.rid) = 1
    AND (SELECT COUNT(*) FROM candidatos x WHERE x.pid = c.pid) = 1
)
UPDATE registrodiariocaja r
SET pagoid = u.pid
FROM unicos u
WHERE r.registrodiariocajaid = u.rid
  AND NOT EXISTS (SELECT 1 FROM registrodiariocaja y WHERE y.pagoid = u.pid);

-- Auditoría de correcciones -----------------------------------------------
CREATE TABLE IF NOT EXISTS correccioncaja (
  correccioncajaid      INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  correccioncajafecha   TIMESTAMP    NOT NULL DEFAULT NOW(),
  usuarioid             VARCHAR(25)  NOT NULL,
  correccioncajaentidad VARCHAR(10)  NOT NULL,  -- 'VENTA' | 'PAGO'
  correccioncajaentidadid bigint     NOT NULL,
  correccioncajaaccion  VARCHAR(20)  NOT NULL,  -- 'METODO' | 'ANULAR' | 'CARGAR'
  aperturaid            INTEGER,                -- turno afectado
  cierreid              INTEGER,                -- NULL si el turno estaba abierto
  correccioncajamotivo  VARCHAR(250) NOT NULL,
  correccioncajaantes   JSONB,
  correccioncajadespues JSONB
);

CREATE INDEX IF NOT EXISTS idx_correccioncaja_apertura
  ON correccioncaja (aperturaid);
CREATE INDEX IF NOT EXISTS idx_correccioncaja_entidad
  ON correccioncaja (correccioncajaentidad, correccioncajaentidadid);

-- Menús ------------------------------------------------------------------
--   MOVIMIENTOSDIA  consulta de ventas y cobros del día del local (cajeros).
--   CORRECCIONCAJA  corrección de ventas/cobros. "editar" = turno propio
--                   abierto; "eliminar" = turnos cerrados (supervisor).
INSERT INTO menu (MenuId, MenuNombre) VALUES
  ('MOVIMIENTOSDIA', 'MOVIMIENTOSDIA'),
  ('CORRECCIONCAJA', 'CORRECCIONCAJA')
ON CONFLICT (menuid) DO NOTHING;

INSERT INTO perfilmenu (PerfilId, MenuId, puedeCrear, puedeEditar, puedeEliminar, puedeLeer)
VALUES
  (1, 'MOVIMIENTOSDIA', 1, 1, 1, 1),
  (1, 'CORRECCIONCAJA', 1, 1, 1, 1)
ON CONFLICT (perfilid, menuid) DO UPDATE SET
  puedecrear    = EXCLUDED.puedecrear,
  puedeeditar   = EXCLUDED.puedeeditar,
  puedeeliminar = EXCLUDED.puedeeliminar,
  puedeleer     = EXCLUDED.puedeleer;

-- Quien hoy puede vender o cobrar puede consultar lo cargado en el día.
INSERT INTO perfilmenu (PerfilId, MenuId, puedeCrear, puedeEditar, puedeEliminar, puedeLeer)
SELECT DISTINCT pm.perfilid, 'MOVIMIENTOSDIA', 0, 0, 0, 1
FROM perfilmenu pm
WHERE pm.menuid IN ('NUEVAVENTA', 'APERTURACAJA', 'PAGOS')
  AND pm.puedeleer = 1
  AND pm.perfilid <> 1
ON CONFLICT (perfilid, menuid) DO NOTHING;

COMMIT;
